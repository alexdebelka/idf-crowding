"""Encode the intro cut as RLE RGB565 frames (apoint/intro_data.h).

Every frame stands alone (no reference to the previous one), so the keychain can decode a frame
band by band without a full-frame buffer. Words: a header with the top bit set is a run
(count in the low 15 bits, then one colour); without it, `count` literal colours follow.
Run: python3 gen/intro_enc.py <folder of f_*.png at 320x170> apoint/intro_data.h
"""

import glob
import sys

import numpy as np
from PIL import Image

src, out = sys.argv[1], sys.argv[2]
files = sorted(glob.glob(f"{src}/f_*.png"))
MAXC = (1 << 15) - 1


def frame(i, f):
    a = np.array(Image.open(f).convert("RGB")).astype(np.int32)
    bg = a[160, 5]
    if np.abs(bg - [216, 247, 73]).sum() < 12 and i > len(files) // 2:
        a[97:121, :, :] = bg  # cover the tagline baked into the video
    return (
        ((a[..., 0] >> 3) << 11 | (a[..., 1] >> 2) << 5 | (a[..., 2] >> 3))
        .astype(np.uint16)
        .ravel()
    )


def enc(v):
    words, i, n = [], 0, len(v)
    while i < n:
        j = i
        while j < n and j - i < MAXC and v[j] == v[i]:
            j += 1
        if j - i >= 2:
            words += [0x8000 | (j - i), int(v[i])]
            i = j
            continue
        lit = []
        while i < n and len(lit) < MAXC and not (i + 1 < n and v[i] == v[i + 1]):
            lit.append(int(v[i]))
            i += 1
        words += [len(lit)] + lit
    return words


words, offs = [], []
for i, f in enumerate(files):
    offs.append(len(words))
    words += enc(frame(i, f))
print(f"{len(files)} frames, {len(words) * 2} bytes", file=sys.stderr)
with open(out, "w") as o:
    o.write(
        "// Generated by gen/intro_enc.py from brand/v2/intro-v2.mp4 "
        "(scene 2.3-5.6 s at 1.3x, 20 fps,\n"
        "// 320x170, tagline covered). RLE RGB565, one stand-alone frame each. Do not edit.\n"
        "#pragma once\n#include <stdint.h>\n\n"
    )
    o.write(f"#define INTRO_FRAMES {len(files)}\n#define INTRO_FPS 20\n")
    offs_list = ",".join(map(str, offs + [len(words)]))
    o.write(f"static const uint32_t intro_offs[INTRO_FRAMES + 1] = {{{offs_list}}};\n")
    o.write("static const uint16_t intro_words[] = {\n")
    for k in range(0, len(words), 16):
        o.write(",".join(str(w) for w in words[k : k + 16]) + ",\n")
    o.write("};\n")
