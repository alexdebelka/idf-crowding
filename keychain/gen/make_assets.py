"""Fonts and rabbit masks for the keychain firmware.

Writes src/fonts_data.h (Onest, 4-bit alpha glyphs) and src/rabbit_data.h (rabbit mark alpha
masks). Inputs: the Onest woff2 files of the web app (OFL) and the rabbit path of the brand mark.
Run: python3 gen/make_assets.py <onest-latin.woff2> <mark.svg> <out_dir>
Needs: fonttools, brotli, pillow, cairosvg.
"""

import io
import re
import sys

import cairosvg
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

woff2, mark_svg, out_dir = sys.argv[1:4]

ttf = io.BytesIO()
f = TTFont(woff2)
f.flavor = None
f.save(ttf)
TTF = ttf.getvalue()

# name, weight, size (px), letter-spacing (em) applied at draw time
FONTS = [
    ("fh52", 800, 52.0, -0.04),
    ("fh40", 800, 40.0, -0.04),
    ("fh28", 800, 28.0, -0.035),
    ("fname", 700, 15.0, -0.005),  # station name
    ("fsmall", 650, 12.0, 0.0),  # legend, hour labels
    ("fsmallb", 800, 12.0, 0.0),  # highlighted hour labels
    ("fsmallm", 700, 12.0, 0.0),  # "+n", setup status
    ("fbadge", 800, 10.5, -0.02),  # line badges
    ("fpill", 700, 12.0, 0.0),  # date pill
    ("flabel", 600, 13.0, 0.0),  # setup labels, messages
    ("fvalue", 700, 20.0, -0.01),  # setup values
]
CHARS = [chr(c) for c in range(32, 127)] + list("àâäçéèêëîïôöùûüÿœæÀÂÇÉÈÊÎÔÛŒ–—’·«»°…")


def font(weight, size):
    ft = ImageFont.truetype(io.BytesIO(TTF), size)
    ft.set_variation_by_axes([weight])
    return ft


lines = [
    "// Generated by gen/make_assets.py from Onest (SIL Open Font License 1.1, see OFL.txt). "
    "Do not edit.",
    "#pragma once",
    '#include "gfx.h"',
    "",
]
for name, weight, size, track in FONTS:
    ft = font(weight, size)
    ascent, descent = ft.getmetrics()
    bits = bytearray()
    glyphs = []
    for ch in CHARS:
        pad = int(size) + 4
        im = Image.new("L", (pad * 3, pad * 3), 0)
        ImageDraw.Draw(im).text((pad, pad * 2), ch, font=ft, fill=255, anchor="ls")
        bbox = im.getbbox()
        adv = ft.getlength(ch)
        if bbox is None:
            glyphs.append((ord(ch), len(bits), 0, 0, 0, 0, round(adv * 64)))
            continue
        x0, y0, x1, y1 = bbox
        g = im.crop(bbox)
        w, h = g.size
        px = list(g.getdata())
        q = [min(15, (v + 8) // 17) for v in px]
        if len(q) % 2:
            q.append(0)
        off = len(bits)
        for i in range(0, len(q), 2):
            bits.append(q[i] << 4 | q[i + 1])
        glyphs.append((ord(ch), off, w, h, x0 - pad, y0 - pad * 2, round(adv * 64)))
    lines.append(f"static const uint8_t {name}_bits[{len(bits)}] = {{")
    for i in range(0, len(bits), 24):
        lines.append(",".join(str(b) for b in bits[i : i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const Glyph {name}_glyphs[{len(glyphs)}] = {{")
    for g in glyphs:
        lines.append("{" + ",".join(str(v) for v in g) + "},")
    lines.append("};")
    lines.append(
        f"static const Font {name.upper()} = {{{name}_glyphs, {len(glyphs)}, {name}_bits, "
        f"{ascent}, {descent}, {size}f, {track * size:.3f}f}};"
    )
    lines.append("")
    print(name, len(bits), "bytes", file=sys.stderr)
with open(f"{out_dir}/fonts_data.h", "w") as f:
    f.write("\n".join(lines) + "\n")

# Rabbit: the brand mark path in the square box the mockups use (viewBox -67 -128 134 134).
with open(mark_svg) as f:
    svg = f.read()
d = re.search(r'<path d="([^"]+)"', svg).group(1)
out = [
    "// Generated by gen/make_assets.py from brand/v2/mark.svg. Do not edit.",
    "#pragma once",
    "#include <stdint.h>",
    "",
]
for px in (20, 42, 50, 62):
    s = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="-67 -128 134 134" '
        f'width="{px}" height="{px}">'
        f'<path fill="#000" fill-rule="evenodd" d="{d}"/></svg>'
    )
    png = cairosvg.svg2png(bytestring=s.encode(), output_width=px, output_height=px)
    a = Image.open(io.BytesIO(png)).getchannel("A")
    out.append(f"static const uint8_t rabbit{px}[{px * px}] = {{")
    data = list(a.getdata())
    for i in range(0, len(data), px):
        out.append(",".join(str(v) for v in data[i : i + px]) + ",")
    out.append("};")
with open(f"{out_dir}/rabbit_data.h", "w") as f:
    f.write("\n".join(out) + "\n")
