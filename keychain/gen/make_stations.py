"""Station list for the keychain's setup page (apoint/src/stations_data.h).

Reads the app's index (app/public/data/index.json, built by `make score`) and writes the id, name
and line names of every Place, so the setup page can offer a station search without Internet.
Run: python3 gen/make_stations.py ../app/public/data/index.json apoint/src/stations_data.h
"""

import json
import sys

index, out = sys.argv[1:3]
with open(index, encoding="utf-8") as f:
    places = json.load(f)["places"]
rows = []
for p in sorted(places, key=lambda p: p["name"]):
    seen, lines = set(), []
    for line in p.get("lines", []):
        if line["name"] not in seen:
            seen.add(line["name"])
            lines.append(line["name"])
    rows.append([str(p["id"]), p["name"], " ".join(lines)])
js = "const S=" + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";"
with open(out, "w", encoding="utf-8") as o:
    o.write(
        "// Generated by gen/make_stations.py from the app's index.json. Do not edit.\n"
        "#pragma once\n\n"
    )
    o.write(f"// {len(rows)} stations: [id, name, lines]\n")
    o.write('static const char STATIONS_JS[] = R"APT(' + js + ')APT";\n')
print(len(rows), "stations,", len(js.encode()), "bytes", file=sys.stderr)
